# ------------------------------------------------------------------ examples

def region_cells(name: str, lab: LabGrid) -> frozenset:
    """The cells of a region: lab_grid.json's "room1", "door", "room2", or a flyable region "<room>_fly"."""
    if name in CODE:
        return frozenset(lab.regions[name])
    if name.endswith("_fly"):
        f = ROOT / "grid" / f"{name.removesuffix('_fly')}_flyable.json"
        return frozenset(tuple(c) for c in json.loads(f.read_text())["cells"])
    raise SystemExit(f"unknown region {name!r}")


def load_example(example_dir: Path, lab: LabGrid | None = None) -> dict:
    d = Path(example_dir).resolve()
    ex = json.loads((d / "example.json").read_text())
    lab = lab or load_lab_grid()
    ex["dir"] = d
    ex["tree_path"] = d / ex["tree"]
    ex["goal"] = network_goal(ex["goal_from"])
    ex["start_cells"] = frozenset().union(*(region_cells(r, lab) for r in ex["start_regions"]))
    ex["safe_cells"] = frozenset().union(*(region_cells(r, lab) for r in ex["safe_regions"]))
    return ex


def network_goal(name: str, labels_json: Path = ASTAR_LABELS_JSON) -> tuple[int, int]:
    """The cell the network ``name`` was trained to converge to (networks/astar_labels.json)."""
    return tuple(json.loads(labels_json.read_text())["goals_xy"][name])


# ------------------------------------------------------------------ pieces of a .tree

def header(title: str, generator: str, sources: str) -> str:
    return (f"#{{ {title} Generated by {generator} from {sources}; do not edit by hand.\n"
            "   Cells are (x, y), x east, y north. A proof about this model is a statement about this grid\n"
            "   and these networks, not about the room or a flight. }#\n")


def cellmap_decl(lab: LabGrid) -> str:
    lines = "\n".join(f"\tcondition {{(eq, index_var, {i})}} assign{{result{{{c}}}}}"
                      for i, c in enumerate(lab.cellmap) if c != 0)
    return ("    #{ cellmap[y * W + x]: 0 obstacle, 1 Room 1, 2 doorway, 3 Room 2, 4 free but unreachable }#\n"
            "    variable { env cellmap DEFINE INT static array (mult, W, H) iterative_assign, index_var\n"
            f"{lines}\n\tassign{{result{{0}}}}\n    }}")


def member_decl(lab: LabGrid, name: str, cells, comment: str) -> str:
    """A static array ``name[y * W + x]``: 1 on ``cells``, 0 everywhere else."""
    lines = "\n".join(f"\tcondition {{(eq, index_var, {y * lab.W + x})}} assign{{result{{1}}}}" for x, y in sorted(cells))
    return (f"    #{{ {comment} }}#\n"
            f"    variable {{ env {name} DEFINE INT static array (mult, W, H) iterative_assign, index_var\n"
            f"{lines}\n\tassign{{result{{0}}}}\n    }}")


def start_decl(lab: LabGrid, cells, comment: str) -> str:
    """x_d, y_d start on any of ``cells``. The set is spelled out per x: BehaVerify does not allow an array lookup
    inside a loop's such_that."""
    xs = sorted({x for x, _ in cells})
    ys_for = {x: sorted(y for cx, y in cells if cx == x) for x in xs}
    cases = "\n".join(
        f"\tcase {{(eq, x_d, {x})}} result{{(loop, loop_var, {{{', '.join(map(str, ys))}}} such_that True, loop_var)}}"
        for x, ys in ys_for.items())
    return (f"    #{{ {comment} }}#\n"
            f"    variable {{ env x_d VAR [0, (sub, W, 1)] assign{{result{{(loop, loop_var, {{{', '.join(map(str, xs))}}} "
            "such_that True, loop_var)}}}\n"
            f"    variable {{ env y_d VAR [0, (sub, H, 1)] assign{{\n{cases}\n\tresult{{0}}}}}}")


def neural_decl(nets: dict) -> str:
    """One NEURAL classification variable per network, read by argmax over ACTIONS, inputs the blackboard copy
    (x_cur, y_cur) of the drone's cell: BehaVerify's python generator reads every network input from the blackboard."""
    return "\n".join(f"""    variable {{ bl {name} NEURAL classification {{{', '.join(repr(a) for a in ACTIONS)}}}
\tinputs {{x_cur, y_cur}}
\tconfig {{
\t    table
\t}}
\tsource {{
\t    '{src}'
\t}}
    }}""" for name, src in nets.items())


#: the grid-world move, as in the NeuS 2025 grid world: one cell per tick, clamped to the grid's bounds and NOT
#: blocked by obstacles, so a move into an obstacle is visible to the safety specification.
