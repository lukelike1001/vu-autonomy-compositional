def net_sources(tree_dir: Path, names) -> dict:
    """``{name: path of networks/<name>.onnx relative to the .tree file}``: BehaVerify resolves it from the tree."""
    rel = Path("..") / ".." / "networks" if tree_dir.parent == EXAMPLES else None
    if rel is None:
        raise SystemExit(f"{tree_dir} is not an example directory under {EXAMPLES}")
    return {n: str(rel / f"{n}.onnx") for n in names}


# ------------------------------------------------------------------ running a BehaVerify-generated tree

class GeneratedTree:
    """``behaverify python TREE`` in a temporary folder, imported, ready to be started from any cell and ticked with
    the generated runner's own ``full_tick`` (pre-tick update, tick, delayed actions, post-tick update)."""

    def __init__(self, tree: Path, behaverify: Path | None = None):
        self.tree = Path(tree).resolve()
        self.stem = self.tree.stem
        self._tmp = tempfile.TemporaryDirectory()
        bv = behaverify or Path(sys.executable).parent / "behaverify"
        r = subprocess.run([str(bv), "python", str(self.tree), self._tmp.name, "--overwrite"],
                           capture_output=True, text=True)
        if r.returncode != 0:
            raise SystemExit(f"behaverify python failed on {self.tree.name}:\n{r.stderr[-2000:]}")
        self.pydir = str(Path(self._tmp.name) / "python")
        sys.path.insert(0, self.pydir)
        self.mod = importlib.import_module(self.stem)
        self.env_mod = importlib.import_module(f"{self.stem}_environment")
        self.runner = importlib.import_module(f"{self.stem}_runner")
        self.rand_mod = importlib.import_module("serene_randomizer")

    def start(self, cell):
        """A fresh blackboard, environment and tree, with the drone placed on ``cell``. Returns (bb, env, tree)."""
        import py_trees
        py_trees.blackboard.Blackboard.clear()
        rnd = self.rand_mod.serene_randomizer()
        bb = self.mod.create_blackboard(rnd)
        env = getattr(self.env_mod, f"{self.stem}_environment")(bb)
        rnd.set_blackboard_and_environment(bb, env)
        self.mod.initialize_blackboard(bb)
        env.initialize_environment()
        tree = py_trees.trees.BehaviourTree(self.mod.create_tree(env))
        if cell is not None:
            env.x_d, env.y_d = cell
        return bb, env, tree

    def tick(self, tree, env):
        self.runner.full_tick(tree, env)

    def route(self, cell, max_ticks: int = 200):
        """The cells the tree drives the drone through from ``cell``, one per tick, until it chooses XX (stays).
        Returns (cells, acts): cells[0] is the start, acts[i] the tree's action on tick i+1."""
        bb, env, tree = self.start(cell)
        cells, acts = [tuple(cell)], []
        for _ in range(max_ticks):
            self.tick(tree, env)
            acts.append(bb.act)
            here = (env.x_d, env.y_d)
            if bb.act == "XX":
                return cells, acts
            cells.append(here)
        raise RuntimeError(f"no XX within {max_ticks} ticks from {cell}: {cells[-5:]}")

    def close(self):
        if self.pydir in sys.path:
            sys.path.remove(self.pydir)
        for m in [m for m in sys.modules if m.startswith(self.stem) or m == "serene_randomizer" or m.endswith("_file")]:
            del sys.modules[m]
        self._tmp.cleanup()


def simulate(ex: dict, lab: LabGrid, ticks: int) -> dict:
    """Start the generated tree on EVERY cell of the start set and tick it ``ticks`` times. A run fails if it ever
    stands outside the safe set, never reaches the goal, or is not at the goal at the end. With ``must_pass`` (a
    region) and ``must_pass_from`` (regions), a run that starts in one of those must also pass through it."""
    g = GeneratedTree(ex["tree_path"])
    try:
        _, env0, _ = g.start(None)
        if hasattr(env0, "cellmap") and tuple(env0.cellmap) != lab.cellmap:
            raise SystemExit(f"{ex['tree']}: the tree's cellmap differs from grid/lab_grid.json; regenerate it")
        goal, safe = ex["goal"], ex["safe_cells"]
        must = region_cells(ex["must_pass"], lab) if ex.get("must_pass") else None
        must_from = frozenset().union(*(region_cells(r, lab) for r in ex.get("must_pass_from", [])))
        starts = sorted(ex["start_cells"], key=lambda c: (c[1], c[0]))
        fails, longest = [], 0
        for s in starts:
            bb, env, tr = g.start(s)
            path, reached, unsafe = [s], None, None
            for t in range(1, ticks + 1):
                g.tick(tr, env)
                c = (env.x_d, env.y_d)
                path.append(c)
                if c not in safe and unsafe is None:
                    unsafe = (t, c, getattr(bb, "act", None))
                if c == goal and reached is None:
                    reached = t
            passed = must is None or s not in must_from or any(c in must for c in path)
            stayed = path[-1] == goal
            if reached is not None:
                longest = max(longest, reached)
            if unsafe or reached is None or not stayed or not passed:
                fails.append({"start": list(s), "unsafe_at": unsafe, "reached_goal_at": reached,
                              "at_goal_at_end": stayed, "passed_must": passed, "end": list(path[-1])})
        return {"tree": ex["tree"], "goal": list(goal), "starts": len(starts), "ticks": ticks,
                "failures": len(fails), "longest_to_goal": longest,
                "unsafe_runs": sum(1 for f in fails if f["unsafe_at"]),
                "no_goal_runs": sum(1 for f in fails if f["reached_goal_at"] is None or not f["at_goal_at_end"]),
                "first_failures": fails[:3]}
    finally:
        g.close()
