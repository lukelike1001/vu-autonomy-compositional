"""What every NSBT example shares: the lab grid in BehaVerify's DSL, the networks' declaration, the grid-world
movement, and running a BehaVerify-generated tree from a cell.

Each example (``examples/<name>/``) has a ``generate_tree.py`` that writes its ``.tree`` from these pieces, and an
``example.json`` that says what the tree must do:

    {"tree": "room1_nn1.tree",            the tree, next to example.json
     "goal_from": "room1_fly",            the goal: astar_labels.json's goals_xy[goal_from]
     "start_regions": ["room1_fly"],      the start set (the simulation starts from every one of its cells)
     "safe_regions": ["room1_fly"],       the cells it may stand on

A region is "room1", "door" or "room2" (lab_grid.json), or "<room>_fly": the cells of grid/<room>_flyable.json, the
part of a room the Neo 2 host's own 0.60 m clearance test accepts (grid/flyable.py).
     "flight": {...}}                     what hardware/neo2_nsbt.py flies (optional)

Cells are (x, y): x east, y north, (0, 0) the south-west cell of the whole-lab grid (``grid/lab_grid.py``).
"""
