#!/usr/bin/env python3
"""Write the two-room NSBT as a BehaVerify ``.tree`` file, from the grid and the three networks.

The tree (after the NeuS 2025 grid world, ``REPRODUCIBILITY/2025_NEUS/examples/grid_world/template.tree``):

    Root (sequence)
    ├── Assign   reads the drone's cell from the environment: x_cur, y_cur := x_d, y_d and
    │            region := 'R1' if y_d > DOOR_Y, 'D' if y_d == DOOR_Y, else 'R2'
    └── Act      act := room1(x_cur, y_cur) if region = 'R1', door(...) if 'D', room2(...) if 'R2'

The networks read the blackboard copy (``x_cur, y_cur``), not ``x_d, y_d``: BehaVerify's python generator reads
every network input from the blackboard, so a network fed environment variables does not run in python.

The environment then moves the drone one cell in the direction ``act`` (as in the NeuS grid world: clamped to the
grid's bounds and NOT blocked by obstacles, so a move into an obstacle is visible to the safety specification).

``cellmap`` is the whole-lab grid as an array indexed by ``y * W + x``: 0 obstacle, 1 Room 1, 2 doorway, 3 Room 2,
4 free but unreachable. The drone starts on any cell with ``cellmap`` 1, 2 or 3.

Specifications:

* ``INVARSPEC`` safety: the drone never stands on an obstacle cell (``cellmap != 0``), from any of the 116 starts.
* ``CTLSPEC`` liveness: ``AG ((x_d, y_d) = START -> AF (x_d, y_d) = GOAL)``: from the start cell (default (16, 13),
  the middle of Room 1's rightmost column) the drone eventually reaches NN2's goal.

The y-test in ``Assign`` is a shortcut that is exact for THIS grid only (the doorway is the only free cell in its
row); ``check_split`` refuses to write a tree if it ever disagrees with the regions in ``lab_grid.json``.

    python3 tree/generate_tree.py              # writes two_rooms_nsbt.tree next to this script
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "grid"))
from lab_grid import DOOR, LAB_GRID_JSON, REGIONS, ROOM1, ROOM2, LabGrid, load_lab_grid  # noqa: E402

ACTIONS = ("We", "Ea", "No", "So", "XX")
ASTAR_LABELS_JSON = ROOT / "networks" / "astar_labels.json"
TREE_FILE = HERE / "two_rooms_nsbt.tree"


def nn2_goal(labels_json: Path = ASTAR_LABELS_JSON) -> tuple[int, int]:
    """The cell NN2 was trained to converge to."""
    return tuple(json.loads(labels_json.read_text())["goals_xy"]["room2"])


def check_split(lab: LabGrid):
    door_y = lab.door[1]
    for name, code in (("room1", ROOM1), ("door", DOOR), ("room2", ROOM2)):
        for (x, y) in lab.regions[name]:
            by_y = ROOM1 if y > door_y else DOOR if y == door_y else ROOM2
            if by_y != code:
                raise SystemExit(f"the y-split disagrees with the grid at ({x}, {y}): y says {by_y}, grid says {code}")


def tree_text(lab: LabGrid, goal, start, nets: dict) -> str:
    W, H, door, cellmap = lab.W, lab.H, lab.door, lab.cellmap
    door_x, door_y = door
    gx, gy = goal
    starts_x = sorted({x for i, c in enumerate(cellmap) if c in (1, 2, 3) for x in [i % W]})
    # the start set spelled out per x (BehaVerify does not allow an array lookup inside a loop's such_that)
    ys_for = {x: sorted(i // W for i, c in enumerate(cellmap) if c in (1, 2, 3) and i % W == x) for x in starts_x}
    start_y_cases = "\n".join(
        f"\tcase {{(eq, x_d, {x})}} result{{(loop, loop_var, {{{', '.join(map(str, ys))}}} such_that True, loop_var)}}"
        for x, ys in ys_for.items())
    cell = "(index, cellmap, (add, (mult, y_d, W), x_d))"
    cellmap_lines = "\n".join(f"\tcondition {{(eq, index_var, {i})}} assign{{result{{{c}}}}}"
                              for i, c in enumerate(cellmap) if c != 0)
    neural = "\n".join(f"""    variable {{ bl {name} NEURAL classification {{{', '.join(repr(a) for a in ACTIONS)}}}
\tinputs {{x_cur, y_cur}}
\tconfig {{
\t    table
\t}}
\tsource {{
\t    '{src}'
\t}}
    }}""" for name, src in nets.items())
    return f"""#{{ Two-room grid world NSBT. Generated by tree/generate_tree.py from grid/lab_grid.json and
   networks/*.onnx; do not edit by hand.
   Cells are (x, y), x east, y north. A proof about this model is a statement about this grid
   and these networks, not about the room or a flight. }}#
configuration {{
    neural
}}
enumerations {{
    {', '.join(repr(a) for a in ACTIONS)}, 'R1', 'D', 'R2'
}}
constants {{
    W := {W}, H := {H}, DOOR_X := {door_x}, DOOR_Y := {door_y}, GOAL_X := {gx}, GOAL_Y := {gy}, START_X := {start[0]}, START_Y := {start[1]}
}} end_constants

variables {{
    variable {{ bl act VAR {{{', '.join(repr(a) for a in ACTIONS)}}} assign{{result{{'XX'}}}}}}
    variable {{ bl region VAR {{'R1', 'D', 'R2'}} assign{{result{{'R1'}}}}}}
    #{{ the cell the tree believes it is in: copied from the environment by Assign on every tick }}#
    variable {{ bl x_cur VAR [0, (sub, W, 1)] assign{{result{{0}}}}}}
    variable {{ bl y_cur VAR [0, (sub, H, 1)] assign{{result{{0}}}}}}
    #{{ cellmap[y * W + x]: 0 obstacle, 1 Room 1, 2 doorway, 3 Room 2, 4 free but unreachable }}#
    variable {{ env cellmap DEFINE INT static array (mult, W, H) iterative_assign, index_var
{cellmap_lines}
\tassign{{result{{0}}}}
    }}
    #{{ the start: any cell of Room 1, the doorway or Room 2 }}#
    variable {{ env x_d VAR [0, (sub, W, 1)] assign{{result{{(loop, loop_var, {{{', '.join(map(str, starts_x))}}} such_that True, loop_var)}}}}}}
    variable {{ env y_d VAR [0, (sub, H, 1)] assign{{
{start_y_cases}
\tresult{{0}}}}}}
{neural}
}} end_variables

environment_update {{
    variable_statement {{
\tx_d
\tassign {{
\t    case {{(eq, act, 'We')}} result {{(max, 0, (sub, x_d, 1))}}
\t    case {{(eq, act, 'Ea')}} result {{(min, (sub, W, 1), (add, x_d, 1))}}
\t    result {{x_d}}
\t}}
    }}
    variable_statement {{
\ty_d
\tassign {{
\t    case {{(eq, act, 'So')}} result {{(max, 0, (sub, y_d, 1))}}
\t    case {{(eq, act, 'No')}} result {{(min, (sub, H, 1), (add, y_d, 1))}}
\t    result {{y_d}}
\t}}
    }}
}} end_environment_update

checks {{
}} end_checks

environment_checks {{
}} end_environment_checks

actions {{
    action {{
\tAssign
\targuments {{}}
\tlocal_variables {{}} end_local_variables
\tread_variables {{}} end_read_variables
\twrite_variables {{region, x_cur, y_cur}} end_write_variables
\tinitial_values {{}} end_initial_values
\tupdate {{
\t    read_environment {{
\t\tread_cell
\t\tcondition {{True}}
\t\tvariable_statement {{
\t\t    x_cur
\t\t    assign {{result {{x_d}}}}
\t\t}}
\t\tvariable_statement {{
\t\t    y_cur
\t\t    assign {{result {{y_d}}}}
\t\t}}
\t\tvariable_statement {{
\t\t    region
\t\t    assign {{
\t\t\tcase {{(gt, y_d, DOOR_Y)}} result {{'R1'}}
\t\t\tcase {{(eq, y_d, DOOR_Y)}} result {{'D'}}
\t\t\tresult {{'R2'}}
\t\t    }}
\t\t}}
\t    }}
\t    return_statement {{
\t\tresult {{success}} end_result
\t    }} end_return_statement
\t}} end_update
    }} end_action
    action {{
\tAct
\targuments {{}}
\tlocal_variables {{}} end_local_variables
\tread_variables {{region, {', '.join(nets)}}} end_read_variables
\twrite_variables {{act}} end_write_variables
\tinitial_values {{}} end_initial_values
\tupdate {{
\t    variable_statement {{
\t\tact
\t\tassign {{
\t\t    case {{(eq, region, 'R1')}} result {{room1}}
\t\t    case {{(eq, region, 'D')}} result {{door}}
\t\t    result {{room2}}
\t\t}}
\t    }}
\t    return_statement {{
\t\tresult {{success}} end_result
\t    }} end_return_statement
\t}} end_update
    }} end_action
}} end_actions

sub_trees {{}} end_sub_trees

tree {{
    composite {{
\tRoot sequence
\tchildren {{
\t    Assign {{}}
\t    Act {{}}
\t}}
    }}
}} end_tree

tick_prerequisite {{ (True) }} end_tick_prerequisite

specifications {{
    #{{ SAFETY: the drone never crashes into an obstacle, whichever network (NN1, the doorway's, NN2) moved it.
       cellmap is 0 exactly on obstacle cells; the grid's border is all obstacle, so leaving the grid is a crash too. }}#
    INVARSPEC {{
\t(neq, {cell}, 0)
    }}
    #{{ LIVENESS: from the start cell (START_X, START_Y), the rightmost of Room 1, the drone eventually reaches the goal
       (GOAL_X, GOAL_Y), where NN2 was trained to converge. Written AG (start -> AF goal) so that it does not depend on
       how BehaVerify's encoding lines up the initial state with the first tick. }}#
    CTLSPEC {{
\t(always_globally, (implies, (and, (eq, x_d, START_X), (eq, y_d, START_Y)), (always_finally, (and, (eq, x_d, GOAL_X), (eq, y_d, GOAL_Y)))))
    }}
}} end_specifications
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--start", default="16,13", help="the liveness start cell x,y (default: the middle of Room 1's "
                    "rightmost column, x = 16)")
    a = ap.parse_args()
    lab, goal = load_lab_grid(LAB_GRID_JSON), nn2_goal()
    check_split(lab)
    start = tuple(int(v) for v in a.start.split(","))
    if lab.code(*start) != ROOM1:
        raise SystemExit(f"the start {start} is not a Room 1 cell")
    nets = {n: f"../networks/{n}.onnx" for n in REGIONS}       # relative to the .tree file
    TREE_FILE.write_text(tree_text(lab, goal, start, nets))
    print(f"wrote tree/{TREE_FILE.name}")
    print(f"  {lab.W} x {lab.H} grid, doorway {lab.door}, start {start}, goal {goal}, "
          f"{sum(c in (ROOM1, DOOR, ROOM2) for c in lab.cellmap)} start cells for safety")


if __name__ == "__main__":
    main()
